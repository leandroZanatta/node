	void bateComACadeia() {

		for (Caso caso : CASOS) {

			MapaDeTicks mapa = MapaDeTicks.de(caso.ticks(), caso.tickMinimo(), caso.tickMaximo(), caso.bloco());
			PoolV3 pool = new PoolV3(caso.sqrtA(), caso.liquidezA(), caso.tickA(), 100, 1).comTicks(mapa);

			boolean zeroParaUm = caso.quantia0().signum() > 0;
			BigInteger entrada = zeroParaUm ? caso.quantia0() : caso.quantia1();
			BigInteger saidaReal = (zeroParaUm ? caso.quantia1() : caso.quantia0()).negate();

			Passo passo = pool.aplicar(zeroParaUm ? Direcao.ZERO_PARA_UM : Direcao.UM_PARA_ZERO, entrada);
			PoolV3 depois = (PoolV3) passo.depois();

			assertEquals(saidaReal, passo.saida(), "saída no bloco " + caso.bloco());
			assertEquals(caso.liquidezB(), depois.liquidez(), "liquidez depois no bloco " + caso.bloco());

			// O preço final bate EXATO nos swaps de entrada exata. O do bloco 124.082.695 foi de SAÍDA exata (o
			// roteador fixou a saída e o contrato arredondou a entrada a partir dela): reproduzido como entrada
			// exata, a saída bate ao wei e o √P fica 4 unidades abaixo em 5,3e26 — menos de 1 wei de entrada no
			// último passo. Nós só fazemos entrada exata; a tolerância aqui é sub-wei, não folga de modelo.
			BigInteger diferenca = caso.sqrtB().subtract(depois.sqrtPrecoX96()).abs();
			org.junit.jupiter.api.Assertions.assertTrue(diferenca.compareTo(BigInteger.valueOf(8)) <= 0,
					"preço depois no bloco " + caso.bloco() + ": diferença " + diferenca);
		}
	}
